#!/usr/bin/env node
/*
 * Export the ink!/WASM coprocessor (built by `make coprocessor`) into
 * sdk/artifacts/coprocessor.json — what the in-app cross-VM deployer and withdraw flow ship:
 * the wasm code, its pallet-contracts code hash, the message selectors, and the withdraw
 * circuit's verifying key as EVM-ordered words (the constructor argument).
 * Pinned by sdk/artifacts/MANIFEST.json.
 *
 *   make coprocessor && cd scripts && node export-coprocessor.js
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { blake2b } from "@noble/hashes/blake2b";
import { bytesToHex } from "@noble/hashes/utils";
import { vkToWords } from "./vk_to_words.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const INK = join(ROOT, "coprocessor", "target", "ink", "umbra_coprocessor");
const wasm = readFileSync(join(INK, "umbra_coprocessor.wasm"));
const meta = JSON.parse(readFileSync(join(INK, "umbra_coprocessor.json"), "utf8"));

// pallet-contracts keys code by blake2-256(wasm); cross-check cargo-contract's metadata.
const codeHash = "0x" + bytesToHex(blake2b(wasm, { dkLen: 32 }));
if (codeHash !== meta.source.hash) throw new Error(`code hash mismatch: ${codeHash} != ${meta.source.hash}`);

const selectors = Object.fromEntries([
  ...meta.spec.constructors.map((c) => [c.label, c.selector]),
  ...meta.spec.messages.map((m) => [m.label, m.selector]),
]);
const vk = JSON.parse(readFileSync(join(ROOT, "sdk", "artifacts", "withdraw_verification_key.json"), "utf8"));

const out = {
  note: "ink!/WASM Groth16 coprocessor; generated by scripts/export-coprocessor.js — do not edit.",
  build: { compiler: meta.source.compiler, cargoContract: meta.source.build_info?.cargo_contract_version ?? null, ink: meta.source.language },
  codeHash,
  selectors,
  withdrawVkWords: vkToWords(vk),
  wasm: "0x" + wasm.toString("hex"),
};
const path = join(ROOT, "sdk", "artifacts", "coprocessor.json");
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
console.log(`umbra_coprocessor ${wasm.length} bytes, code hash ${codeHash}`);
console.log(`wrote ${path}`);
