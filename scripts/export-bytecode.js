#!/usr/bin/env node
/*
 * Export the deployable creation bytecode of every Umbra contract (from `forge build`) plus
 * the circomlibjs Poseidon(2) bytecode into sdk/artifacts/contracts.json — what the in-app
 * native deployer (Portaldot Extension signs) ships. Pinned by sdk/artifacts/MANIFEST.json.
 *
 *   cd contracts && forge build && cd ../scripts && node export-bytecode.js
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { ethers } from "ethers";
import { poseidonContract } from "circomlibjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "..", "contracts", "out");
const code = (n) => JSON.parse(readFileSync(join(OUT, `${n}.sol`, `${n}.json`), "utf8")).bytecode.object;

const contracts = {
  Poseidon2: ethers.hexlify(poseidonContract.createCode(2)),
  WithdrawVerifier: code("WithdrawVerifier"),
  TransactionVerifier: code("TransactionVerifier"),
  UmbraPool: code("UmbraPool"),
  UmbraTokenPool: code("UmbraTokenPool"),
  UmbraShieldedPool: code("UmbraShieldedPool"),
  UmbraCoprocessorBridge: code("UmbraCoprocessorBridge"),
  DeployHarness: code("DeployHarness"), // read-only cost estimation only
};
const path = join(__dirname, "..", "sdk", "artifacts", "contracts.json");
writeFileSync(path, JSON.stringify({ note: "Creation bytecode; generated by scripts/export-bytecode.js — do not edit.", contracts }, null, 2) + "\n");
for (const [k, v] of Object.entries(contracts)) console.log(k.padEnd(20), `${(v.length - 2) / 2} bytes`);
console.log(`wrote ${path}`);
