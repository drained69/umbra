#!/usr/bin/env node
/*
 * Deploy Umbra to Portaldot V3 testnet.
 *
 *   1. Poseidon(2) hasher   — bytecode from circomlibjs, so the on-chain Merkle hash
 *                             matches the circom circuit and the SDK (poseidon-lite).
 *   2. Verifier             — on-chain WithdrawVerifier.sol  (VERIFIER_MODE=onchain)
 *                             OR UmbraCoprocessorBridge      (VERIFIER_MODE=coprocessor)
 *   3. UmbraPoolFactory
 *   4. One UmbraPool per denomination (default 1/10/100 tPOT)
 *
 * Writes deployments/portaldot-v3.json consumed by the frontend, relayer, and SDK.
 *
 * Prereqs: `forge build` in contracts/ (for verifier + factory artifacts); `npm i` here.
 */
import "dotenv/config";
import { ethers } from "ethers";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import circomlibjs from "circomlibjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const OUT = join(ROOT, "contracts", "out");

const RPC = process.env.PORTALDOT_RPC || "https://test-evm-rpc-v3.portaldot.dev";
const CHAIN_ID = Number(process.env.PORTALDOT_CHAIN_ID || 420420777);
const DECIMALS = BigInt(process.env.POT_DECIMALS || 14);
const LEVELS = Number(process.env.TREE_LEVELS || 20);
const MODE = (process.env.VERIFIER_MODE || "onchain").toLowerCase();
const DENOMS = (process.env.DENOMINATIONS || "1,10,100").split(",").map((s) => s.trim());

function artifact(name, file) {
  const p = join(OUT, `${file}.sol`, `${name}.json`);
  const j = JSON.parse(readFileSync(p, "utf8"));
  return { abi: j.abi, bytecode: j.bytecode.object };
}

async function deploy(wallet, { abi, bytecode }, args = []) {
  const f = new ethers.ContractFactory(abi, bytecode, wallet);
  const c = await f.deploy(...args);
  await c.waitForDeployment();
  return c;
}

async function main() {
  if (!process.env.PRIVATE_KEY) throw new Error("set PRIVATE_KEY in .env");
  const provider = new ethers.JsonRpcProvider(RPC, CHAIN_ID);
  const wallet = new ethers.Wallet(process.env.PRIVATE_KEY, provider);
  console.log(`deployer: ${wallet.address}`);
  console.log(`balance : ${ethers.formatUnits(await provider.getBalance(wallet.address), DECIMALS)} tPOT`);

  // 1. Poseidon(2) — deploy raw bytecode generated by circomlibjs.
  console.log("deploying Poseidon(2) hasher...");
  const posBytecode = circomlibjs.poseidonContract.createCode(2);
  const posAbi = circomlibjs.poseidonContract.generateABI(2);
  const posFactory = new ethers.ContractFactory(posAbi, posBytecode, wallet);
  const poseidon = await posFactory.deploy();
  await poseidon.waitForDeployment();
  const hasher = await poseidon.getAddress();
  console.log(`  Poseidon: ${hasher}`);

  // 2. Verifier
  let verifier;
  if (MODE === "coprocessor") {
    console.log("deploying UmbraCoprocessorBridge (cross-VM WASM verify)...");
    const c = await deploy(wallet, artifact("UmbraCoprocessorBridge", "UmbraCoprocessorBridge"), [
      process.env.COPROCESSOR_ADDRESS || ethers.ZeroAddress,
      process.env.ATTESTOR_ADDRESS || wallet.address,
    ]);
    verifier = await c.getAddress();
  } else {
    console.log("deploying on-chain WithdrawVerifier...");
    const c = await deploy(wallet, artifact("WithdrawVerifier", "verifiers/WithdrawVerifier"));
    verifier = await c.getAddress();
  }
  console.log(`  Verifier (${MODE}): ${verifier}`);

  // 3. Factory
  console.log("deploying UmbraPoolFactory...");
  const factory = await deploy(wallet, artifact("UmbraPoolFactory", "UmbraPoolFactory"), [verifier, hasher, LEVELS]);
  const factoryAddr = await factory.getAddress();
  console.log(`  Factory: ${factoryAddr}`);

  // 4. Pools
  const pools = {};
  for (const d of DENOMS) {
    const denomWei = ethers.parseUnits(d, DECIMALS);
    console.log(`creating pool ${d} tPOT (${denomWei} wei)...`);
    const tx = await factory.createPool(denomWei);
    await tx.wait();
    pools[d] = await factory.poolForDenomination(denomWei);
    console.log(`  pool ${d} tPOT: ${pools[d]}`);
  }

  const deployment = {
    network: "portaldot-v3-testnet",
    chainId: CHAIN_ID,
    rpc: RPC,
    decimals: Number(DECIMALS),
    verifierMode: MODE,
    treeLevels: LEVELS,
    relayerFeeBps: Number(process.env.RELAYER_FEE_BPS || 50),
    contracts: { poseidon: hasher, verifier, factory: factoryAddr, pools },
    deployedAt: new Date().toISOString(),
    deployer: wallet.address,
  };
  const dir = join(ROOT, "deployments");
  mkdirSync(dir, { recursive: true });
  const path = join(dir, "portaldot-v3.json");
  writeFileSync(path, JSON.stringify(deployment, null, 2));
  // Mirror into the frontend so the app picks up addresses automatically.
  mkdirSync(join(ROOT, "frontend", "src", "config"), { recursive: true });
  writeFileSync(join(ROOT, "frontend", "src", "config", "deployment.json"), JSON.stringify(deployment, null, 2));
  console.log(`\nwrote ${path} (and frontend/src/config/deployment.json)`);
  console.log("done.");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
