#!/usr/bin/env node
/*
 * Generate contracts/src/PoseidonZeros.sol: the empty-subtree hashes for each Merkle level,
 * computed with Poseidon(2) from ZERO_VALUE = keccak256("umbra.v3.zero") % FIELD.
 *
 * Why constants: on Portaldot every new storage slot locks ~3.84 tPOT (pallet-revive
 * depositPerByte = 0.06 tPOT). Caching these in storage cost 21 slots per pool instance.
 * Hard-coding them (as Tornado does) costs ~0 per instance.
 */
const fs = require("fs");
const path = require("path");
const { poseidon2 } = require("poseidon-lite");

const FIELD = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const ZERO_VALUE = 17003957365552116588566697242255183877916613397757664392656876041027752888120n;
const MAX_LEVELS = 20; // must cover the circuits' tree depth

const z = [ZERO_VALUE];
for (let i = 1; i <= MAX_LEVELS; i++) z.push(poseidon2([z[i - 1], z[i - 1]]) % FIELD);

const branches = z
  .map((v, i) => `        ${i === 0 ? "if" : "else if"} (i == ${i}) return 0x${v.toString(16).padStart(64, "0")};`)
  .join("\n");

const sol = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// AUTO-GENERATED by circuits/scripts/gen_zeros.js — do not edit by hand.
/// @title PoseidonZeros
/// @notice Empty-subtree hashes: zeros(0) = ZERO_VALUE = keccak256("umbra.v3.zero") % FIELD,
///         zeros(i) = Poseidon(zeros(i-1), zeros(i-1)). Hard-coded so pools don't spend
///         Portaldot storage deposits (~3.84 tPOT per slot) caching them.
library PoseidonZeros {
    uint256 internal constant MAX_LEVELS = ${MAX_LEVELS};

    error LevelOutOfRange();

    function zeros(uint256 i) internal pure returns (uint256) {
${branches}
        else revert LevelOutOfRange();
    }
}
`;
const out = path.join(__dirname, "..", "..", "contracts", "src", "PoseidonZeros.sol");
fs.writeFileSync(out, sol);
console.log(`wrote ${path.relative(process.cwd(), out)} (${MAX_LEVELS + 1} levels)`);
