#!/usr/bin/env node
/*
 * Wraps a snarkjs-generated Groth16 verifier so it implements Umbra's IVerifier
 * (dynamic `uint256[] publicSignals`). Used for BOTH the withdraw and transaction
 * circuits, so the inner contract name is made unique per circuit to avoid collisions
 * when Foundry compiles all verifier files together.
 *
 * usage: adapt_verifier.js <raw.sol> <out.sol> <ContractName>
 */
const fs = require("fs");

const [, , inPath, outPath, contractName] = process.argv;
if (!inPath || !outPath || !contractName) {
  console.error("usage: adapt_verifier.js <raw.sol> <out.sol> <ContractName>");
  process.exit(1);
}

let raw = fs.readFileSync(inPath, "utf8");
const nMatch = raw.match(/uint\[(\d+)\]\s+calldata\s+_pubSignals/);
if (!nMatch) {
  console.error("could not detect public-signal count in snarkjs output");
  process.exit(1);
}
const N = parseInt(nMatch[1], 10);
const innerName = `${contractName}Inner`;
raw = raw.replace(/contract\s+Groth16Verifier/, `contract ${innerName}`);

const adapter = `
// ---------------------------------------------------------------------------
// Umbra adapter: exposes the snarkjs verifier through IVerifier so the pools can
// stay VM-agnostic (this on-chain verifier OR the WASM coprocessor bridge).
// Auto-generated by circuits/scripts/adapt_verifier.js — do not edit by hand.
// ---------------------------------------------------------------------------
import {IVerifier} from "../interfaces/IVerifier.sol";

contract ${contractName} is IVerifier {
    ${innerName} public immutable inner;

    constructor() {
        inner = new ${innerName}();
    }

    function verifyProof(
        uint256[2] calldata a,
        uint256[2][2] calldata b,
        uint256[2] calldata c,
        uint256[] calldata publicSignals
    ) external view returns (bool) {
        require(publicSignals.length == ${N}, "bad pubSignals len");
        uint256[${N}] memory fixedSignals;
        for (uint256 i = 0; i < ${N}; i++) {
            fixedSignals[i] = publicSignals[i];
        }
        return inner.verifyProof(a, b, c, fixedSignals);
    }
}
`;

fs.writeFileSync(outPath, raw + "\n" + adapter);
console.log(`wrote ${outPath} (contract ${contractName}, public signals: ${N})`);
